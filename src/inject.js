"use strict";
// Patching and restoring one Discord `resources` directory.
//
// How injection works (the same layout other Electron client mods use):
//
//   resources/app.asar   ->  resources/_app.asar      (Discord's original app, untouched)
//                            resources/app/           (AesDc's shim: package.json, index.js, aesdc.json)
//
// Electron loads `resources/app/` in preference to `app.asar`. The shim starts the AesDc runtime
// (which hooks Discord's windows so Corrode loads from their preload) and then boots the original
// `_app.asar` exactly as Electron would have. Ejecting is the reverse: move `_app.asar` back and
// delete `resources/app/`. Nothing inside Discord's archive is ever modified.
//
// This file is also copied into the user's data directory and required by the runtime inside
// Discord, so it may only depend on Node built-ins and ./fsx and ./asar.
const path = require("node:path");
const { spawn } = require("node:child_process");
const { fs, exists, isDir, readJson, rm, copy } = require("./fsx");
const asar = require("./asar");

const MARKER = "aesdc.json";
const APP_ASAR = "app.asar";
const BACKUP_ASAR = "_app.asar";

class InjectError extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

function paths(resourcesDir) {
  return {
    appAsar: path.join(resourcesDir, APP_ASAR),
    backupAsar: path.join(resourcesDir, BACKUP_ASAR),
    appDir: path.join(resourcesDir, "app"),
    marker: path.join(resourcesDir, "app", MARKER),
  };
}

/**
 * Describe the injection state of a resources directory.
 *
 * - `clean`: stock Discord.
 * - `injected`: AesDc is installed.
 * - `outdated`: AesDc is installed, but Discord (or a package manager) has since written a new
 *   `app.asar`. The shim already prefers the new archive, so Discord keeps working; `repair`
 *   re-injects properly.
 * - `foreign`: `resources/app/` exists but AesDc did not create it (another client mod).
 * - `broken`: neither archive is where it should be.
 * - `missing`: not a Discord resources directory.
 */
function inspect(resourcesDir) {
  const p = paths(resourcesDir);
  const hasAppAsar = exists(p.appAsar);
  const hasBackup = exists(p.backupAsar);
  const hasAppDir = isDir(p.appDir);
  const marker = hasAppDir ? readJson(p.marker, null) : null;
  const ours = !!(marker && marker.aesdc);

  let state;
  if (hasAppDir && !ours) state = "foreign";
  else if (ours) state = hasAppAsar ? "outdated" : hasBackup ? "injected" : "broken";
  else if (hasAppAsar) state = "clean";
  else if (hasBackup) state = "broken"; // half-finished eject: _app.asar without app/
  else state = "missing";

  return {
    resourcesDir,
    state,
    hasAppAsar,
    hasBackup,
    /** A `_app.asar` left behind next to a real `app.asar` (safe to delete). */
    leftoverBackup: hasAppAsar && hasBackup && !ours,
    marker: ours ? marker : null,
    runtimeMissing: ours && marker.hostMain ? !exists(marker.hostMain) : false,
  };
}

function moveAsar(from, to) {
  fs.renameSync(from, to);
  if (exists(`${from}.unpacked`)) {
    rm(`${to}.unpacked`);
    fs.renameSync(`${from}.unpacked`, `${to}.unpacked`);
  }
}

function removeAsar(file, deferred) {
  for (const p of [file, `${file}.unpacked`]) {
    if (!exists(p)) continue;
    try {
      rm(p);
    } catch (err) {
      if (!isLockError(err)) throw err;
      deferred.push(p);
    }
  }
}

function isLockError(err) {
  return ["EPERM", "EBUSY", "EACCES"].includes(err && err.code) && process.platform === "win32";
}

/** Fields of Discord's package.json that are safe to mirror into the shim's package.json. */
const MIRRORED_FIELDS = ["name", "productName", "version", "description", "author", "license", "homepage", "desktopName"];

function shimPackageJson(originalPkg) {
  const out = {};
  for (const k of MIRRORED_FIELDS) if (originalPkg[k] !== undefined) out[k] = originalPkg[k];
  out.main = "index.js";
  return JSON.stringify(out, null, 2) + "\n";
}

function shimSource({ hostMain, dataDir, version }) {
  return `// Generated by AesDc ${version}. Do not edit: \`aesdc uninstall\` removes this folder and restores Discord.
"use strict";
const path = require("path");
const fs = require("original-fs");
const { app } = require("electron");

const HOST_MAIN = ${JSON.stringify(hostMain)};
const DATA_DIR = ${JSON.stringify(dataDir)};

const resources = path.join(__dirname, "..");
// If Discord or a package manager wrote a fresh app.asar after AesDc was installed, it is newer
// than the _app.asar backup, so prefer it.
const fresh = path.join(resources, "app.asar");
const asar = fs.existsSync(fresh) ? fresh : path.join(resources, "_app.asar");
const pkg = require(path.join(asar, "package.json"));
const entry = path.join(asar, pkg.main || "index.js");

try {
  if (fs.existsSync(HOST_MAIN)) {
    require(HOST_MAIN).start({ asar, resources, shimDir: __dirname, dataDir: DATA_DIR, pkg });
  } else {
    console.warn("[AesDc] runtime not found at " + HOST_MAIN + "; starting Discord without Corrode. Run \`aesdc repair\`.");
  }
} catch (err) {
  console.error("[AesDc] runtime failed to start; starting Discord without Corrode.", err);
}

// Boot the original app exactly as Electron would have.
if (typeof app.setAppPath === "function") app.setAppPath(asar);
require.main.filename = entry;
require(entry);
`;
}

/**
 * Inject AesDc into `resourcesDir`. Idempotent: re-running refreshes the shim, and an
 * `outdated` install (Discord replaced app.asar) is re-injected around the new archive.
 *
 * @param {string} resourcesDir
 * @param {{ hostMain: string, dataDir: string, version: string }} opts
 */
function inject(resourcesDir, opts) {
  const s = inspect(resourcesDir);
  const p = paths(resourcesDir);
  if (s.state === "missing") throw new InjectError("ENOTDISCORD", `${resourcesDir} does not contain app.asar; is this a Discord install?`);
  if (s.state === "foreign")
    throw new InjectError(
      "EFOREIGN",
      `${p.appDir} was created by another client mod. Uninstall that mod first (it restores app.asar), then install AesDc.`,
    );
  if (s.state === "broken" && !s.hasBackup)
    throw new InjectError("EBROKEN", `No app.asar or _app.asar in ${resourcesDir}. Reinstall Discord, then install AesDc.`);

  let moved = false;
  if (s.hasAppAsar) {
    // app.asar is the authoritative original; any _app.asar next to it is older.
    const deferred = [];
    removeAsar(p.backupAsar, deferred);
    if (deferred.length) throw new InjectError("ELOCKED", `${p.backupAsar} is in use. Close Discord and try again.`);
    try {
      moveAsar(p.appAsar, p.backupAsar);
    } catch (err) {
      if (isLockError(err)) throw new InjectError("ELOCKED", `${p.appAsar} is in use. Close Discord and try again.`);
      throw err;
    }
    moved = true;
  }

  try {
    let pkg;
    try {
      pkg = asar.readJson(p.backupAsar, "package.json");
    } catch (err) {
      throw new InjectError("EBADASAR", `Could not read Discord's package.json from ${p.backupAsar}: ${err.message}`);
    }
    const tmp = path.join(resourcesDir, `app.aesdc-${process.pid}.tmp`);
    rm(tmp);
    fs.mkdirSync(tmp);
    fs.writeFileSync(path.join(tmp, "package.json"), shimPackageJson(pkg));
    fs.writeFileSync(path.join(tmp, "index.js"), shimSource(opts));
    fs.writeFileSync(
      path.join(tmp, MARKER),
      JSON.stringify(
        {
          aesdc: opts.version,
          injectedAt: new Date().toISOString(),
          hostMain: opts.hostMain,
          dataDir: opts.dataDir,
          discordVersion: pkg.version,
        },
        null,
        2,
      ) + "\n",
    );
    rm(p.appDir);
    fs.renameSync(tmp, p.appDir);
  } catch (err) {
    if (moved) {
      // Put Discord back the way we found it.
      try {
        rm(p.appDir);
        moveAsar(p.backupAsar, p.appAsar);
      } catch {}
    }
    throw err;
  }
  return inspect(resourcesDir);
}

/**
 * Restore the original Discord in `resourcesDir`. Idempotent and safe on a clean install.
 *
 * Inside a running Discord on Windows, `_app.asar` is locked by the process. In that case the
 * archive is copied back to `app.asar` instead of renamed, and the locked leftovers are returned in
 * `deferred` so the caller can delete them once Discord exits (see `removeLater`).
 *
 * @returns {{ state: string, deferred: string[] }}
 */
function eject(resourcesDir) {
  const s = inspect(resourcesDir);
  const p = paths(resourcesDir);
  const deferred = [];
  if (s.state === "missing") return { state: s.state, deferred };
  if (s.state === "foreign") throw new InjectError("EFOREIGN", `${p.appDir} was not created by AesDc; leaving it alone.`);

  if (s.hasAppAsar) {
    // Discord already has a real app.asar (clean install, or it updated itself): drop our backup.
    removeAsar(p.backupAsar, deferred);
  } else if (s.hasBackup) {
    try {
      moveAsar(p.backupAsar, p.appAsar);
    } catch (err) {
      if (!isLockError(err)) throw err;
      const tmp = `${p.appAsar}.aesdc.tmp`;
      fs.copyFileSync(p.backupAsar, tmp);
      fs.renameSync(tmp, p.appAsar);
      if (exists(`${p.backupAsar}.unpacked`)) copy(`${p.backupAsar}.unpacked`, `${p.appAsar}.unpacked`);
      removeAsar(p.backupAsar, deferred);
    }
  } else if (s.marker) {
    throw new InjectError("EBROKEN", `Discord's original app.asar is missing from ${resourcesDir}. Reinstall Discord.`);
  }

  if (s.marker) {
    try {
      rm(p.appDir);
    } catch (err) {
      // With app.asar restored the shim boots stock Discord anyway; finish later.
      if (!isLockError(err)) throw err;
      deferred.push(p.appDir);
    }
  }
  return { state: inspect(resourcesDir).state, deferred };
}

/**
 * Delete files that are locked by a running Discord, after it exits (Windows only). Spawns a hidden
 * detached PowerShell that retries for about two minutes.
 */
function removeLater(files) {
  if (!files.length) return;
  if (process.platform !== "win32") {
    for (const f of files) rm(f);
    return;
  }
  const list = files.map((f) => `'${f.replace(/'/g, "''")}'`).join(",");
  const script =
    `$ps=@(${list}); for($i=0;$i -lt 60;$i++){ $left=@(); ` +
    `foreach($p in $ps){ if(Test-Path -LiteralPath $p){ try{ Remove-Item -LiteralPath $p -Recurse -Force -ErrorAction Stop }catch{ $left+=$p } } }; ` +
    `if($left.Count -eq 0){ break }; $ps=$left; Start-Sleep -Seconds 2 }`;
  spawn("powershell.exe", ["-NoProfile", "-NonInteractive", "-WindowStyle", "Hidden", "-Command", script], {
    detached: true,
    stdio: "ignore",
    windowsHide: true,
  }).unref();
}

module.exports = { inspect, inject, eject, removeLater, InjectError, MARKER, shimSource, shimPackageJson };
